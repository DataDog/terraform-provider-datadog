package emit

import (
	"strings"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

// renderTwilioExampleTest renders the generated test for the Twilio fixture.
// These specs assert on the emitted source, because a template's contract is
// the file it produces — a view assertion cannot catch an unused import or an
// incomplete configuration.
func renderTwilioExampleTest() string {
	_, scenario := twilioExampleView()
	out, err := RenderResourceExampleTest(scenario, twilioResourceView(), twilioAPIPaths())
	Expect(err).To(Succeed())
	return string(out)
}

var _ = Describe("RenderResourceExampleTest", func() {
	It("gofmts, so a template syntax error fails generation rather than the build", func() {
		Expect(renderTwilioExampleTest()).To(HavePrefix("// " + "Generated by tfgen"))
	})

	// gofmt does not remove unused imports, so an unneeded one here would
	// produce a file that formats cleanly and refuses to compile.
	It("imports only what the emitted file uses", func() {
		source := renderTwilioExampleTest()
		block := source[strings.Index(source, "import ("):]
		block = block[:strings.Index(block, ")")]
		for _, path := range strings.Split(block, "\n") {
			path = strings.Trim(strings.TrimSpace(path), `"`)
			if path == "" || path == "import (" {
				continue
			}
			symbol := path[strings.LastIndex(path, "/")+1:]
			body := source[strings.Index(source, "func Test"):]
			Expect(body).To(ContainSubstring(symbol+"."), "import %q is unused", path)
		}
	})

	// Generated from the description rather than recorded, so it is only ever
	// meaningful in replay — and it must skip before provider setup.
	It("guards on replay mode ahead of any provider setup", func() {
		source := renderTwilioExampleTest()
		body := source[strings.Index(source, "func TestAccDatadog"):]
		guard := strings.Index(body, "if !isReplaying()")
		setup := strings.Index(body, "testAccFrameworkMuxProviders")
		Expect(guard).To(BeNumerically(">", 0))
		Expect(guard).To(BeNumerically("<", setup), "the skip must precede provider setup")
	})

	// Without an accessor the destroy check constructs the SDK client itself,
	// which needs the SDK package imported. The import-usage spec above cannot
	// catch the inverse — a used package that is never imported — so this
	// pins it directly.
	It("imports the SDK package when the provider exposes no accessor", func() {
		_, scenario := twilioExampleView()
		view := twilioResourceView()
		view.APIAccessor = ""
		view.APIConstructor = "NewTwilioIntegrationApi"
		out, err := RenderResourceExampleTest(scenario, view, twilioAPIPaths())
		Expect(err).To(Succeed())

		Expect(string(out)).To(ContainSubstring(
			`"github.com/DataDog/datadog-api-client-go/v2/api/datadogV2"`))
		Expect(string(out)).To(ContainSubstring(
			"datadogV2.NewTwilioIntegrationApi(apiInstances.HttpClient)"))
	})

	It("omits that import when an accessor exists", func() {
		Expect(renderTwilioExampleTest()).NotTo(ContainSubstring("datadog-api-client-go"))
	})

	It("wires the generated destroy check as CheckDestroy", func() {
		source := renderTwilioExampleTest()
		Expect(source).To(ContainSubstring(
			"CheckDestroy:             testAccDatadogIntegrationTwilioAccountOpenAPIExampleDestroy(providers.frameworkProvider)"))
	})

	// The cassette's final interaction is a read expecting a 404; this is what
	// consumes it. A read that succeeds means destroy left the object behind.
	It("treats a successful read in the destroy check as a failure", func() {
		source := renderTwilioExampleTest()
		destroy := source[strings.Index(source, "func testAccDatadogIntegrationTwilioAccountOpenAPIExampleDestroy"):]
		Expect(destroy).To(ContainSubstring("httpResp.StatusCode == 404"))
		Expect(destroy).To(ContainSubstring("still exists after destroy"))
		Expect(destroy).To(ContainSubstring("GetTwilioIntegrationApiV2().GetTwilioIntegrationAccount(auth, r.Primary.ID)"))
	})

	Describe("step configurations", func() {
		// A Terraform configuration is the complete desired state, while an
		// update request is the API's sparse PATCH delta. Rendering step 2
		// from its delta alone drops required attributes step 1 set, and the
		// plan fails validation before any interaction is replayed.
		It("renders a later step as the full desired state, not the PATCH delta", func() {
			source := renderTwilioExampleTest()
			step2 := source[strings.Index(source, "ConfigStep2() string"):]
			step2 = step2[:strings.Index(step2, "\n}")]

			Expect(step2).To(ContainSubstring(`name = "twilio-prod-renamed"`))
			Expect(step2).To(ContainSubstring("censor_logs = false"))
			// Carried over from step 1 — required, and absent from the delta.
			Expect(step2).To(ContainSubstring(`account_sid = "ACxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx"`))
			Expect(step2).To(ContainSubstring("auth_type"))
		})

		It("gives each step its own helper and distinct body", func() {
			source := renderTwilioExampleTest()
			Expect(source).To(ContainSubstring("ConfigStep1() string"))
			Expect(source).To(ContainSubstring("ConfigStep2() string"))
			Expect(strings.Count(source, `name = "twilio-prod"`+"\n")).To(Equal(1))
		})

		// Regression: the Terraform name twilio_messages_logs comes from the
		// API name twilio-messages-logs. A suffix match between the two fails,
		// and this dataflow was silently dropped from the configuration while
		// the cassette still sent it.
		It("renders an attribute whose Terraform name was normalized", func() {
			source := renderTwilioExampleTest()
			Expect(source).To(ContainSubstring("dataflows = {"))
			Expect(source).To(ContainSubstring("twilio_messages_logs = {"))
			Expect(source).To(ContainSubstring(
				`"dataflows.twilio_messages_logs.enabled", "true"`))
		})

		It("never writes a declared secret into the file", func() {
			Expect(renderTwilioExampleTest()).NotTo(ContainSubstring("twilio-basic-auth-secret"))
		})
	})

	It("names the cassette and interaction count in the header", func() {
		source := renderTwilioExampleTest()
		Expect(source).To(ContainSubstring(
			"cassettes/TestAccDatadogIntegrationTwilioAccountOpenAPIExample.yaml (7 interactions)"))
	})

	It("propagates a view it cannot build", func() {
		_, scenario := twilioExampleView()
		view := twilioResourceView()
		view.Read.Method = ""
		_, err := RenderResourceExampleTest(scenario, view, twilioAPIPaths())
		Expect(err).To(MatchError(ContainSubstring("no SDK read call")))
	})
})
