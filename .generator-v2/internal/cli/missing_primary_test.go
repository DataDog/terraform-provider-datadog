package cli

import (
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/terraform-providers/terraform-provider-datadog/generator/internal/model"
)

func TestMissingPrimaryFailsOnlyItsArtifact(t *testing.T) {
	for _, tc := range []struct{ name, block string }{
		{"resource", "resource:\n        group: {create: MissingOperation, read: GetThing, delete: DeleteThing}"},
		{"singular", "datasource_singular:\n        group: {read: MissingOperation}"},
		{"list", "datasource_list:\n        artifact_name: broken\n        group: {read: MissingOperation}"},
		{"search", "datasource_singular:\n        group: {search: MissingOperation}"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			specPath, reportPath := filepath.Join(dir, "spec.yaml"), filepath.Join(dir, "report.json")
			body := readThingResourceFixture(t) + "    broken:\n      " + tc.block + "\n"
			if err := os.WriteFile(specPath, []byte(body), 0600); err != nil {
				t.Fatal(err)
			}
			// An unrelated orphan must survive the failed run's reconciliation.
			ghostPath := filepath.Join(dir, "data_source_datadog_ghost.go")
			ghost := "// Code generated by tfgen; DO NOT EDIT.\npackage fwprovider\nfunc NewDatadogGhostDataSource() {}\n"
			if err := os.WriteFile(ghostPath, []byte(ghost), 0600); err != nil {
				t.Fatal(err)
			}
			if err := runTfgen("generate", "--reconcile", "--spec", specPath,
				"--output-root", dir, "--tests-output-root", filepath.Join(dir, "tests"),
				"--examples-output-root", filepath.Join(dir, "examples"),
				"--docs-root", filepath.Join(dir, "docs"), "--report", reportPath); err == nil {
				t.Fatal("expected an artifact failure")
			}
			var report model.RunReport
			if err := json.Unmarshal([]byte(mustRead(t, reportPath)), &report); err != nil {
				t.Fatal(err)
			}
			var healthy, failed bool
			for _, entry := range report.Artifacts {
				if entry.Tag != "Things" {
					t.Errorf("missing owning tag on successful or failed artifact: %+v", entry)
				}
				if entry.Name == "thing" && entry.Status == model.ArtifactStatusCreated {
					healthy = true
				}
				if entry.Name == "broken" && entry.Status == model.ArtifactStatusFailed {
					failed = true
					data, _ := json.Marshal(entry.Diagnostics)
					for _, want := range []string{"Things", "broken", "MissingOperation", "group."} {
						if !strings.Contains(string(data), want) {
							t.Errorf("diagnostics missing %q: %s", want, data)
						}
					}
				}
			}
			if !healthy || !failed {
				t.Fatalf("want healthy and failed artifact entries: %+v", report.Artifacts)
			}
			if _, err := os.Stat(filepath.Join(dir, "resource_datadog_thing.go")); err != nil {
				t.Fatal(err)
			}
			if _, err := os.Stat(ghostPath); err != nil {
				t.Fatalf("reconcile removed orphan: %v", err)
			}
		})
	}
}
