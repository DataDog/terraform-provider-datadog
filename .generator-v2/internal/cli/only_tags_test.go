func TestGenerateRejectsOnlyTagsWithInclude(t *testing.T) {
	err := runTfgen("generate", "--only-tags", "Teams", "--include", "teams", "--spec", "does-not-matter.yaml")
	if err == nil || !strings.Contains(err.Error(), "--only-tags") {
		t.Fatalf("expected --only-tags with --include to be rejected, got %v", err)
	}
}

// onlyTagsLifecycle generates, without --emit-tests, the teams fixture plus two
// cross-tag declarations over the same ListTeams operation (op.Tag is Teams,
// owner tags are "Registry Owner" and "Other"), seeds an orphan with no
// recorded owner, then removes both cross-tag annotations and runs
// generate --only-tags <tag> --reconcile. It returns the per-name report
// statuses and the output root.
func onlyTagsLifecycle(t *testing.T, onlyTags string) (map[string]model.ArtifactStatus, string) {
	t.Helper()
	spec, err := os.ReadFile(filepath.Join("..", "testdata", "mini-oas", "scripts", "gen-test", "teams.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	base := strings.TrimRight(string(spec), "\n") + "\n"
	full := base + `- name: Registry Owner
  x-datadog-tf-generator:
    owned:
      datasource_list:
        artifact_name: owned_teams
        group:
          read: ListTeams
- name: Other
  x-datadog-tf-generator:
    other:
      datasource_list:
        artifact_name: other_teams
        group:
          read: ListTeams
`
	dir := t.TempDir()
	out := filepath.Join(dir, "out")
	run := func(body string, extra ...string) map[string]model.ArtifactStatus {
		specPath, reportPath := filepath.Join(dir, "spec.yaml"), filepath.Join(dir, "report.json")
		if err := os.WriteFile(specPath, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
		args := append([]string{"generate", "--spec", specPath, "--report", reportPath,
			"--output-root", out, "--tests-output-root", filepath.Join(dir, "tests"),
			"--docs-root", filepath.Join(dir, "docs"),
			"--examples-output-root", filepath.Join(dir, "examples")}, extra...)
		if err := runTfgen(args...); err != nil {
			t.Fatal(err)
		}
		var report model.RunReport
		if err := json.Unmarshal([]byte(mustRead(t, reportPath)), &report); err != nil {
			t.Fatal(err)
		}
		status := map[string]model.ArtifactStatus{}
		for _, e := range report.Artifacts {
			// The first entry per name is the artifact; example and test
			// entries that follow it reuse the name.
			if _, seen := status[e.Name]; !seen && e.Kind == model.ArtifactKindDataSource {
				status[e.Name] = e.Status
			}
		}
		return status
	}

	run(full)
	// An orphan generated by an older run that recorded no owner.
	src := "package fwprovider\n\n// Code generated by tfgen; DO NOT EDIT.\n\nfunc " + emit.DatasourceConstructor("unowned") + "() {}\n"
	if err := os.WriteFile(filepath.Join(out, "data_source_datadog_unowned.go"), []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := emit.SyncGeneratedDatasources(filepath.Join(out, "datasources_generated.go"), []string{emit.DatasourceConstructor("unowned")}, false); err != nil {
		t.Fatal(err)
	}
	return run(base, "--only-tags", onlyTags, "--reconcile"), out
}

func assertKept(t *testing.T, out string, names ...string) {
	t.Helper()
	reg := mustRead(t, filepath.Join(out, "datasources_generated.go"))
	for _, name := range names {
		if _, err := os.Stat(filepath.Join(out, "data_source_datadog_"+name+".go")); err != nil {
			t.Errorf("%s was deleted: %v", name, err)
		}
		if !strings.Contains(reg, emit.DatasourceConstructor(name)+",") {
			t.Errorf("registry lost %s:\n%s", name, reg)
		}
	}
}

func TestGenerateOnlyTagsReconcileRetiresByOwnerTag(t *testing.T) {
	status, out := onlyTagsLifecycle(t, "Registry Owner")

	if status["owned_teams"] != model.ArtifactStatusRetired {
		t.Errorf("owned_teams status %q, want retired", status["owned_teams"])
	}
	for _, name := range []string{"teams", "other_teams", "unowned"} {
		if status[name] != model.ArtifactStatusSkipped {
			t.Errorf("%s status %q, want skipped", name, status[name])
		}
	}
	if _, err := os.Stat(filepath.Join(out, "data_source_datadog_owned_teams.go")); !os.IsNotExist(err) {
		t.Errorf("owned_teams should be retired, stat err: %v", err)
	}
	if strings.Contains(mustRead(t, filepath.Join(out, "datasources_generated.go")), emit.DatasourceConstructor("owned_teams")) {
		t.Error("registry kept retired owned_teams")
	}
	assertKept(t, out, "teams", "other_teams", "unowned")
}

// Selecting the operation's own tag must not retire an orphan owned by another
// tag that merely declared an artifact over that operation.
func TestGenerateOnlyTagsReconcileIgnoresOperationTag(t *testing.T) {
	status, out := onlyTagsLifecycle(t, "Teams")

	if status["teams"] != model.ArtifactStatusUnchanged {
		t.Errorf("teams status %q, want unchanged", status["teams"])
	}
	for _, name := range []string{"owned_teams", "other_teams", "unowned"} {
		if status[name] != model.ArtifactStatusSkipped {
			t.Errorf("%s status %q, want skipped", name, status[name])
		}
	}
	assertKept(t, out, "teams", "owned_teams", "other_teams", "unowned")
}
