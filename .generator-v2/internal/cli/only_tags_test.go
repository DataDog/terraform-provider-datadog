func TestGenerateRejectsOnlyTagsWithInclude(t *testing.T) {
	err := runTfgen("generate", "--only-tags", "Teams", "--include", "teams", "--spec", "does-not-matter.yaml")
	if err == nil || !strings.Contains(err.Error(), "--only-tags") {
		t.Fatalf("expected --only-tags with --include to be rejected, got %v", err)
	}
}

// TestGenerateOnlyTagsScopesGenerationAndReconcile runs --only-tags Teams
// --reconcile over a spec with a second annotated tag. Only the Teams artifact
// is generated; the unselected artifact, an orphan of the unselected tag and an
// unattributable stale registration all survive, while the Teams orphan is
// retired.
func TestGenerateOnlyTagsScopesGenerationAndReconcile(t *testing.T) {
	spec, err := os.ReadFile(filepath.Join("..", "testdata", "mini-oas", "scripts", "gen-test", "teams.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	body := strings.TrimRight(string(spec), "\n") + `
- name: Other
  x-datadog-tf-generator:
    other:
      datasource_list:
        artifact_name: other_teams
        group:
          read: ListTeams
`
	dir := t.TempDir()
	specPath := filepath.Join(dir, "spec.yaml")
	if err := os.WriteFile(specPath, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
	out, tests := filepath.Join(dir, "out"), filepath.Join(dir, "tests")
	for _, d := range []string{out, tests} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	genPath := filepath.Join(out, "datasources_generated.go")
	providerTest := filepath.Join(tests, "provider_test.go")
	if err := os.WriteFile(providerTest, []byte("package test\n\nvar testFiles2EndpointTags = map[string]string{\n}\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	seed := func(name, tag string) string {
		path := filepath.Join(out, "data_source_datadog_"+name+".go")
		src := "package fwprovider\n\n// Code generated by tfgen; DO NOT EDIT.\n\nfunc " + emit.DatasourceConstructor(name) + "() {}\n"
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		if _, err := emit.SyncGeneratedDatasources(genPath, []string{emit.DatasourceConstructor(name)}, false); err != nil {
			t.Fatal(err)
		}
		if _, err := emit.InsertEndpointTag(providerTest, emit.EndpointTagTestKey(name), tag, false); err != nil {
			t.Fatal(err)
		}
		return path
	}
	// Attributed to the selected tag on disk, yet still annotated under Other:
	// annotation wins, so it must not be retired.
	otherTeams := seed("other_teams", "teams")
	ghostTeams := seed("ghost_teams", "teams")
	ghostOther := seed("ghost_other", "other")
	if _, err := emit.SyncGeneratedDatasources(genPath, []string{emit.DatasourceConstructor("stale")}, false); err != nil {
		t.Fatal(err)
	}
	otherBefore := mustRead(t, otherTeams)

	reportPath := filepath.Join(dir, "report.json")
	if err := runTfgen("generate", "--only-tags", "Teams", "--reconcile", "--spec", specPath,
		"--output-root", out, "--tests-output-root", tests,
		"--docs-root", filepath.Join(dir, "docs"),
		"--examples-output-root", filepath.Join(dir, "examples"),
		"--report", reportPath); err != nil {
		t.Fatal(err)
	}

	var report model.RunReport
	if err := json.Unmarshal([]byte(mustRead(t, reportPath)), &report); err != nil {
		t.Fatal(err)
	}
	status := map[string]model.ArtifactStatus{}
	for _, e := range report.Artifacts {
		if e.Kind == model.ArtifactKindDataSource {
			status[e.Name] = e.Status
		}
	}
	if status["teams"] != model.ArtifactStatusCreated {
		t.Errorf("teams status %q, want created", status["teams"])
	}
	if status["other_teams"] != model.ArtifactStatusSkipped {
		t.Errorf("other_teams status %q, want skipped", status["other_teams"])
	}
	if status["ghost_teams"] != model.ArtifactStatusRetired {
		t.Errorf("ghost_teams status %q, want retired", status["ghost_teams"])
	}
	if status["ghost_other"] != model.ArtifactStatusSkipped {
		t.Errorf("ghost_other status %q, want skipped", status["ghost_other"])
	}

	if _, err := os.Stat(ghostTeams); !os.IsNotExist(err) {
		t.Errorf("selected-tag orphan should be retired, stat err: %v", err)
	}
	if _, err := os.Stat(ghostOther); err != nil {
		t.Errorf("unselected-tag orphan was deleted: %v", err)
	}
	if got := mustRead(t, otherTeams); got != otherBefore {
		t.Error("unselected artifact was rewritten")
	}
	reg := mustRead(t, genPath)
	for _, name := range []string{"teams", "other_teams", "ghost_other", "stale"} {
		if !strings.Contains(reg, emit.DatasourceConstructor(name)+"\n") && !strings.Contains(reg, emit.DatasourceConstructor(name)+",") {
			t.Errorf("registry lost %s:\n%s", name, reg)
		}
	}
	if strings.Contains(reg, emit.DatasourceConstructor("ghost_teams")) {
		t.Errorf("registry kept retired ghost_teams:\n%s", reg)
	}
}
